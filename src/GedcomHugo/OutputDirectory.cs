namespace GedcomHugo;

/// <summary>
/// The output directory belongs to gedcom-hugo and is rebuilt from scratch on
/// every run. A marker file proves ownership, so a mistyped --out can never
/// wipe a folder of hand-written content.
/// </summary>
public static class OutputDirectory
{
    public const string MarkerFile = ".gedcom-hugo-output";

    public static void Prepare(string path)
    {
        var full = Path.GetFullPath(path);

        if (Directory.Exists(full))
        {
            var hasEntries = Directory.EnumerateFileSystemEntries(full).Any();
            var ours = File.Exists(Path.Combine(full, MarkerFile));
            if (hasEntries && !ours)
                throw new InvalidOperationException(
                    $"Refusing to clear '{full}': it isn't empty and wasn't created by gedcom-hugo. " +
                    "Point --out at an empty or new folder (conventionally site/_generated).");

            Directory.Delete(full, recursive: true);
        }

        Directory.CreateDirectory(full);
        File.WriteAllText(Path.Combine(full, MarkerFile),
            "Generated by gedcom-hugo. Everything in this folder is deleted and rewritten on each run; don't edit it.\n");
    }
}
